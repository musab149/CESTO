export const useLanguageStore = create<LanguageState>()(
  persist(
    (set, get) => ({
      lang: 'en',
      setLang: (lang) => set({ lang }),
      t: (key: string) => {
        const { lang } = get();
        return translations[lang][key] ?? key;
      },
    }),
    { name: 'cesto-lang' },
  ),
);
