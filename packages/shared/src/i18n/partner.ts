/**
 * Partner dashboard translations, shared by the web partner surface and the
 * mobile partner mode.
 *
 * The dictionaries live here rather than in either app because both render the
 * same screens against the same partner API. Keeping two copies meant a string
 * corrected in one app stayed wrong in the other, and nothing would have caught
 * it — a missing key renders as the key itself, not as an error.
 *
 * The `usePartnerT()` HOOK deliberately does NOT live here. It reads the app's
 * language store, and web and mobile each have their own; each app wraps
 * `partnerT` with a three-line hook of its own instead.
 *
 * A missing key returns the key, mirroring the customer stores' fallback: a
 * visibly wrong label is easier to spot and fix than a blank space.
 */

