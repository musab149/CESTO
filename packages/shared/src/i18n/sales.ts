/**
 * Look up one rep string. Unknown keys come back as themselves — a visibly
 * wrong label is easier to spot than a blank space.
 *
 * `vars` fills `{{name}}` placeholders. Plurals are handled by the caller
 * picking `_one` or `_other`, which is as much grammar as these screens need.
 */
export function salesT(
  lang: SalesLang,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const table = lang === 'es' ? ES : EN;
  const raw = table[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{\{(\w+)\}\}/g, (match, name: string) => (
    name in vars ? String(vars[name]) : match
  ));
}

